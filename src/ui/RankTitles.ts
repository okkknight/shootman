const FINAL_TITLE = '这个世界上已经没有你甩不了的锅了';

export function getSlapbackTitle(score: number): string {
  const rank = Math.max(0, Math.floor(score));
  if (rank < RANK_TITLES.length) {
    return RANK_TITLES[rank];
  }
  return FINAL_TITLE;
}

export function isLegendaryRank(score: number): boolean {
  return Math.max(0, Math.floor(score)) >= RANK_TITLES.length;
}
